import type { Minutes } from "./clock";

/**
 * 🧠内心（設計書8章、本セッションでの決定）。
 *
 * **やることリストではない。** 仕事は📋やること（`types/task.ts`）が持つ。
 * ここに並ぶのは感情と体の感覚と個人的な欲求だけ — 腹が減った、少し眠い、
 * 妻と話したい、今日はなんとなく気分が重い。
 *
 * 基本的にはプレイヤーへの情報と演出でしかない。ただし空腹や疲労を無視し
 * 続ければ、体調そのものが動いて、後の判断や出来事に間接的に効いてくる。
 *
 * 内心が人物像を決めることはない。人物像は、実際に何をしたかが積み上がって
 * 後からできる（`data/tendencies.ts`）。
 */
export interface Concern {
  id: string;
  /** 一行。主語は自分で、命令形にはしない。 */
  text: string;
  /** この時刻から気になりはじめる。 */
  from?: Minutes;
  /** この時刻を過ぎたら、もう気にしない（間に合わなかった、を含む）。 */
  until?: Minutes;
  /** 疲労がこれを超えたときだけ出る。体の感覚は時計ではなく体から来る。 */
  whenFatigueOver?: number;
  /** 空腹がこれを超えたときだけ出る。 */
  whenHungerOver?: number;
  /** これらが全て立っているときだけ出る。 */
  requiresFlags?: string[];
  /** どれか一つでも立っていたら出ない。済んだか、手遅れになったか。 */
  unlessFlags?: string[];
}
