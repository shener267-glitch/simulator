import type { Minutes } from "./clock";

/**
 * 内心（設計書8章、本セッションでの決定）。
 *
 * ToDoリストではない。「やらなければいけないこと」ではなく、本人が
 * 「気になっている」ことを一行で出すだけで、消化するボタンも、済んだ数も、
 * 達成率もない。無視して一日を終えることができる。
 *
 * ただし、無視したことは後で形になって返ってくる — 朝に資料を読まなければ
 * 11:00の党幹部との会談で選べる手が減る。ゲームがそれを咎めることはなく、
 * ただ、そのときに手がないだけになる。
 */
export interface Concern {
  id: string;
  /** 一行。主語は自分で、命令形にはしない。 */
  text: string;
  /** この時刻から気になりはじめる。 */
  from?: Minutes;
  /** この時刻を過ぎたら、もう気にしない（間に合わなかった、を含む）。 */
  until?: Minutes;
  /** これらが全て立っているときだけ出る。 */
  requiresFlags?: string[];
  /** どれか一つでも立っていたら出ない。済んだか、手遅れになったか。 */
  unlessFlags?: string[];
}
