/**
 * 国家運営シミュレーションの時計（設計書2章・v0.3）。
 *
 * v0.2までは「06:00始まりで24:00に閉じる一日」を分オフセットで持っていた。
 * 今回は複数日にまたがる可能性があるゲームなので、起点を実際のカレンダー
 * 日付に置き、そこからの経過分ですべての時刻を表す。
 *
 * 開始日は2024年10月1日（火）。石破内閣が発足した実際の日付
 * ——首班指名は同日の国会本会議、内閣発足はその夜——【事実】。
 * ゲームの一日は、その最初のフル稼働日として朝から始まる、という
 * ゲーム上の設定にしてある（発足式典そのものの分刻みの再現ではない）。
 */
export type Minutes = number;

/** 起点。2024-10-01 00:00 からの経過分ですべての時刻を表す。 */
export const GAME_START = { year: 2024, month: 10, day: 1 } as const;

/** 一日の分数。日付の繰り上がり計算に使う。 */
export const MINUTES_IN_DAY = 1440;

/** ゲームが実際に始まる時刻。朝から一日が動き出す。 */
export const DAY_START_MINUTES = 7 * 60; // 07:00

export type Speed = 1 | 2 | 5 | 10;

/**
 * 時計の状態。再生・一時停止・倍速はプレイヤーが操作する
 * （設計書2章）。分そのものはtickでのみ進む。
 */
export interface Clock {
  totalMinutes: Minutes;
  running: boolean;
  speed: Speed;
}
